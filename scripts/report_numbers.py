def expected_deck_strings(n: dict) -> List[Tuple[str, str]]:
    """(label, text that must appear) - formatted the way the deck prints them."""
    out = []
    for key, _ in DECK_ALGOS:
        r = n["e1"][key]
        out += [
            (f"{key} cost", f"{r['total_cost']:.2f}"),
            (f"{key} travel time", f"{r['total_travel_time']:.1f} min"),
            (f"{key} distance", f"{r['total_distance']:.1f} km"),
        ]
    h = n["e1_headline"]
    out += [
        ("km fewer vs Greedy", f"{h['km_fewer_vs_greedy_pct']}%"),
        ("cost below Greedy", f"{h['cost_below_greedy_pct']}%"),
        ("cost below GA", f"{h['cost_below_ga_pct']}%"),
        ("cost below PSO", f"{h['cost_below_pso_pct']}%"),
        ("Greedy costs more", f"{h['greedy_costs_more_pct']}%"),
    ]
    return out


def expected_paper_strings(n: dict) -> List[Tuple[str, str]]:
    """The paper's E1 table prints each metric to two decimals."""
    out = []
    for key, r in n["e1"].items():
        out += [
            (f"{key} cost", f"{r['total_cost']:.2f}"),
            (f"{key} travel time", f"{r['total_travel_time']:.2f}"),
            (f"{key} distance", f"{r['total_distance']:.2f}"),
        ]
    return out


def find_missing(text: str, expected: List[Tuple[str, str]]) -> List[Tuple[str, str]]:
    return [(label, s) for label, s in expected if s not in text]


def extract_pptx_text(path: Path) -> str:
    from pptx import Presentation

    def walk(shapes):
        for sh in shapes:
            if sh.shape_type == 6:
                yield from walk(sh.shapes)
            else:
                yield sh

    parts = []
    for slide in Presentation(str(path)).slides:
        for sh in walk(slide.shapes):
            if sh.has_text_frame:
                parts.append(sh.text_frame.text)
            if getattr(sh, "has_table", False) and sh.has_table:
                parts += [c.text for row in sh.table.rows for c in row.cells]
        if slide.has_notes_slide:
            parts.append(slide.notes_slide.notes_text_frame.text)
    return "\n".join(parts)


def extract_docx_text(path: Path) -> str:
    import docx

    d = docx.Document(str(path))
    parts = [p.text for p in d.paragraphs]
    for t in d.tables:
        parts += [c.text for row in t.rows for c in row.cells]
    return "\n".join(parts)


def write_outputs(n: dict) -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "report_numbers.json").write_text(json.dumps(n, indent=2), encoding="utf8")
    (OUT_DIR / "report_numbers.md").write_text(render_markdown(n), encoding="utf8")


def _report(kind: str, path: str, missing: List[Tuple[str, str]], total: int) -> int:
    if not missing:
        print(f"OK: {kind} '{path}' contains all {total} expected figures.")
        return 0
    print(f"DRIFT: {kind} '{path}' is missing {len(missing)} of {total} expected figures:")
    for label, s in missing:
        print(f"  - {label}: expected '{s}'")
    return 1


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check-deck", metavar="PPTX")
    parser.add_argument("--check-paper", metavar="DOCX")
    args = parser.parse_args(argv)

    numbers = build_numbers()
    if not (args.check_deck or args.check_paper):
        write_outputs(numbers)
        print(f"Wrote {OUT_DIR / 'report_numbers.json'} and report_numbers.md")
        return 0

    status = 0
    if args.check_deck:
        exp = expected_deck_strings(numbers)
        status |= _report("deck", args.check_deck, find_missing(extract_pptx_text(Path(args.check_deck)), exp), len(exp))
    if args.check_paper:
        exp = expected_paper_strings(numbers)
        status |= _report("paper", args.check_paper, find_missing(extract_docx_text(Path(args.check_paper)), exp), len(exp))
    return status


if __name__ == "__main__":
    sys.exit(main())
